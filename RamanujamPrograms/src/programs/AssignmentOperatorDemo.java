package programs;

public class AssignmentOperatorDemo {

	public static void main(String[] args) {
		
		int a =5;
		
		a+= 5;
		System.out.println("Adding and assigning"+a);
		
		a-= 5;
		System.out.println("Subtracting and assigning"+a);
		
		a*= 5;
		System.out.println("Multiplying  and assigning"+a);
		
		a/= 5;
		System.out.println("Dividing and assigning"+a);
		
		a%= 5;
		System.out.println("Remainder and assigning"+a);
	}

}
